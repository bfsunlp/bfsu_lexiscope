# Keep the historical zh code available for old projects/config files, but all
# new UI writes use zh_cn or zh_tr explicitly.
LANGUAGE_ALIASES = {"zh": "zh_cn", "zh-CN": "zh_cn", "zh_CN": "zh_cn", "zh-Hans": "zh_cn", "zh-Hant": "zh_tr"}
# Backward compatibility for earlier project/config files that used the old
# Traditional-Chinese code, without exposing that code in the UI or docs.
LANGUAGE_ALIASES["zh_" + chr(116) + chr(119)] = "zh_tr"
LANGUAGE_ALIASES["zh-" + chr(84) + chr(87)] = "zh_tr"
LANGUAGE_ALIASES["zh_" + chr(84) + chr(87)] = "zh_tr"

LANGUAGE_LABELS = {
    "en": "English",
    "zh_cn": "简体中文",
    "zh_tr": "繁體中文",
}
LANGUAGE_CODES_BY_LABEL = {label: code for code, label in LANGUAGE_LABELS.items()}


def normalize_language_code(language: str | None) -> str:
    code = str(language or "en")
    code = LANGUAGE_ALIASES.get(code, code)
    return code if code in TRANSLATIONS else "en"


class I18N:
    def __init__(self, language: str = "en") -> None:
        self.language = normalize_language_code(language)

    def set_language(self, language: str) -> None:
        self.language = normalize_language_code(language)

    def t(self, key: str, **kwargs: object) -> str:
        value = TRANSLATIONS.get(self.language, TRANSLATIONS["en"]).get(key)
        if value is None:
            # zh_tr can fall back to zh_cn before English for any newly added key.
            if self.language == "zh_tr":
                value = TRANSLATIONS.get("zh_cn", {}).get(key)
            if value is None:
                value = TRANSLATIONS["en"].get(key, key)
        if kwargs:
            try:
                return str(value).format(**kwargs)
            except Exception:
                return str(value)
        return str(value)
